/**
 * Writes the Spanish word-frequency list into `lib/dictionary/spanish-frequency.ts` (RL-81). Senses list
 * their translations in the dictionary's own order; the list puts the commonest first («decir» before
 * «poner»).
 *
 * Source: hermitdave/FrequencyWords, OpenSubtitles 2018 Spanish `es_50k.txt`, at the path given as the
 * first argument — never downloaded by this script. Licensed CC BY-SA 4.0. Only the words are kept, one
 * per line in rank order; a word's rank is its line.
 *
 * Run: npm run es-frequency:build -w apps/wordbook -- <path to es_50k.txt>
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const source = process.argv[2];
if (source === undefined) throw new Error("Pass the path to es_50k.txt.");

const words: string[] = [];
const seen = new Set<string>();
for (const line of readFileSync(source, "utf8").split("\n")) {
  const word = line.split(" ")[0].toLowerCase();
  if (!/^\p{L}+$/u.test(word) || seen.has(word)) continue;
  seen.add(word);
  words.push(word);
}

const header = `/**
 * GENERATED by apps/wordbook/scripts/build-spanish-frequency.ts. Do not hand-edit.
 * Rerun with the source downloaded beside it: npm run es-frequency:build -w apps/wordbook -- <es_50k.txt>.
 *
 * Derived from hermitdave/FrequencyWords, OpenSubtitles 2018 Spanish es_50k.txt
 * (https://github.com/hermitdave/FrequencyWords), licensed CC BY-SA 4.0
 * (https://creativecommons.org/licenses/by-sa/4.0/). This list, a derived work of a share-alike source,
 * carries the same licence. Its credit is shown at /cuenta (components/account/account-info.tsx).
 *
 * ${words.length} words, commonest first, one per line; a word's rank is its line.
 */
`;
const body = `export const SPANISH_FREQUENCY_WORDS = ${JSON.stringify(words.join("\n"))};\n`;
writeFileSync(path.join(import.meta.dirname, "../lib/dictionary/spanish-frequency.ts"), header + body);
console.log(`${words.length} words`);
